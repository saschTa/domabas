package main

import (
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"log/slog"
	"os"
	"os/signal"
	"syscall"
	"time"

	"github.com/domabas/domabas/backend/internal/config"
	documentworkflows "github.com/domabas/domabas/backend/internal/domain/document/workflows"

	temporaldata "github.com/domabas/domabas/backend/internal/data/temporal"
	"github.com/google/uuid"
	"go.temporal.io/sdk/client"
)

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	logger := slog.New(slog.NewJSONHandler(os.Stderr, nil))
	if err := run(ctx, os.Args[1:], os.Stdout, logger); err != nil {
		logger.Error("workflow diagnostic failed", "error", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, args []string, output io.Writer, logger *slog.Logger) error {
	flags := flag.NewFlagSet("workflow", flag.ContinueOnError)
	accountID := flags.String("account-id", "", "account UUID owning the document")
	id := flags.String("document-id", "", "existing document UUID to read")
	workflowID := flags.String("workflow-id", "", "unique workflow ID (generated by default)")
	enqueueOnly := flags.Bool("enqueue-only", false, "print workflow/run IDs without waiting; remote timeout still applies")
	waitID := flags.String("wait-workflow-id", "", "wait for an existing workflow instead of starting one")
	runID := flags.String("run-id", "", "specific run to wait for, with --wait-workflow-id")
	timeout := flags.Duration("timeout", 30*time.Second, "local wait and new workflow execution timeout")
	if err := flags.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return nil
		}
		return err
	}
	if flags.NArg() != 0 || *timeout <= 0 || *timeout > 10*time.Minute {
		return errors.New("provide flags only and a timeout between 0 and 10m")
	}
	if *waitID != "" {
		if *accountID != "" || *id != "" || *workflowID != "" || *enqueueOnly {
			return errors.New("--wait-workflow-id cannot be combined with document/start options")
		}
	} else {
		if account, err := uuid.Parse(*accountID); err != nil || account == uuid.Nil {
			return errors.New("--account-id must be a UUID")
		}
		if _, err := uuid.Parse(*id); err != nil {
			return errors.New("--document-id must be a UUID")
		}
		if *runID != "" {
			return errors.New("--run-id requires --wait-workflow-id")
		}
	}
	settings, err := config.Load()
	if err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, *timeout)
	defer cancel()
	source, err := temporaldata.NewTemporalDataSource(ctx, settings.TemporalAddress, settings.TemporalNamespace, logger)
	if err != nil {
		return err
	}
	defer source.Close()
	var execution client.WorkflowRun
	if *waitID != "" {
		execution = source.Client().GetWorkflow(ctx, *waitID, *runID)
	} else {
		if *workflowID == "" {
			*workflowID = "domabas-diagnostic-" + uuid.NewString()
		}
		execution, err = source.Client().ExecuteWorkflow(ctx, client.StartWorkflowOptions{
			ID: *workflowID, TaskQueue: settings.TemporalTaskQueue, WorkflowExecutionTimeout: *timeout,
			WorkflowExecutionErrorWhenAlreadyStarted: true,
		}, documentworkflows.DocumentMetadataWorkflowName, documentworkflows.DocumentMetadataRequest{AccountID: *accountID, DocumentID: *id})
		if err != nil {
			return fmt.Errorf("start metadata workflow: %w", err)
		}
		if *enqueueOnly {
			return json.NewEncoder(output).Encode(struct {
				WorkflowID string `json:"workflowId"`
				RunID      string `json:"runId"`
			}{execution.GetID(), execution.GetRunID()})
		}
	}
	var metadata documentworkflows.DocumentMetadataResult
	if err := execution.Get(ctx, &metadata); err != nil {
		if *waitID == "" && ctx.Err() != nil {
			// Waiting expiring does not cancel remote execution. Terminate only
			// the exact run this invocation created, using an uncancelled scope.
			cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 5*time.Second)
			defer cleanupCancel()
			cleanupErr := source.Client().TerminateWorkflow(cleanupCtx, execution.GetID(), execution.GetRunID(), "diagnostic caller stopped waiting")
			if cleanupErr != nil {
				return errors.Join(err, fmt.Errorf("terminate owned workflow: %w", cleanupErr))
			}
		}
		return fmt.Errorf("wait for metadata workflow: %w", err)
	}
	return json.NewEncoder(output).Encode(metadata)
}
