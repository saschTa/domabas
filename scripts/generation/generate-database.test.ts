import { afterEach, expect, test } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { changedFiles } from "./check-generated.ts";
import { databaseFiles, databaseTables, databaseOutput, databaseSnapshot, normalizeDatabaseFile, normalizeDatabaseOutput, rawDatabaseFiles, validateSchemaHelper, withOwnedGenerationSchema } from "./generate-database.ts";

const schema = `domabas_generate_${"a".repeat(32)}`;
const marker = "// Code generated by go-jet DO NOT EDIT.\n\n";
const model = marker + "package model\n\ntype Documents struct {\n\tTitle string\n}\n";
const table = marker + `package table\n\nvar Documents = newDocumentsTable("${schema}", "documents", "")\n`;
function tableType(name: string): string { return name.split("_").map(part => part[0]!.toUpperCase() + part.slice(1)).join(""); }
const helper = marker + 'package table\n\nfunc UseSchema(schema string) {\n' + databaseTables.map(name => { const type = tableType(name); return `\t${type} = ${type}.FromSchema(schema)\n`; }).join("") + '}\n';
function fixture(name: string, kind: "model" | "table"): string {
 const type = tableType(name);
 return kind === "model" ? model.replaceAll("Documents", type) : table.replaceAll("Documents", type).replaceAll("documents", name);
}
async function writeRawTree(output: string): Promise<void> {
 for (const name of databaseTables) for (const kind of ["model", "table"] as const) await Bun.write(join(output, `${kind}/${name}.go`), fixture(name, kind));
 await Bun.write(join(output, "table/table_use_schema.go"), helper);
}
const temporary: string[] = [];
async function directory(): Promise<string> { const path = await mkdtemp(join(tmpdir(), "domabas-db-generator-test-")); temporary.push(path); return path; }
afterEach(async () => { await Promise.all(temporary.splice(0).map(path => rm(path, { recursive: true, force: true }))); });

test("normalizes exactly the pinned constructor and keeps generated marker", () => {
  const output = normalizeDatabaseFile(table, "table/documents.go", schema);
  expect(output).toContain('newDocumentsTable("", "documents", "")');
  expect(output).toStartWith(marker);
  expect(output).not.toContain(schema);
  for (const source of [table.replace("newDocumentsTable", "changed"), table + table, table + `var accidental = "${schema}"\n`, table.replace(marker, "")]) {
    expect(() => normalizeDatabaseFile(source, "table/documents.go", schema)).toThrow();
  }
  expect(() => normalizeDatabaseFile(marker + `package model\nvar leak = "${schema}"`, "model/documents.go", schema)).toThrow("schema reference");
  expect(() => normalizeDatabaseFile(table, "table/unexpected.go", schema)).toThrow("shape");
});

test("omits only the exact pinned global schema mutation helper", () => {
  expect(() => validateSchemaHelper(helper)).not.toThrow();
  expect(() => validateSchemaHelper(helper.replace("Documents.FromSchema(schema)", "nil"))).toThrow("schema helper");
});

test("strict output tree rejects added or missing files", async () => {
  const root = await directory();
  const output = join(root, "database", schema);
  for (const file of [...rawDatabaseFiles, "table/table_use_schema.go"]) await Bun.write(join(output, file), "generated");
  expect(await databaseOutput(root, schema)).toBe(output);
  await Bun.write(join(root, "database", "outside.go"), "unexpected");
  await expect(databaseOutput(root, schema)).rejects.toThrow("output files");
  await rm(join(root, "database", "outside.go"));
  await rm(join(output, "model/documents.go"));
  await expect(databaseOutput(root, schema)).rejects.toThrow("output files");
});

test("normalizes the raw tree into dedicated model files without changing model contents", async () => {
  const root = await directory();
  const output = join(root, "database", schema);
  await writeRawTree(output);
  expect(await normalizeDatabaseOutput(root, schema)).toBe(output);
  expect([...(await databaseSnapshot(output)).keys()].sort()).toEqual([...databaseFiles].sort());
  expect(await Bun.file(join(output, "model/documents.model.go")).text()).toBe(model);
  expect(await Bun.file(join(output, "table/documents.go")).text()).toBe(table.replace(schema, ""));
  expect(await Bun.file(join(output, "model/documents.go")).exists()).toBe(false);
  expect(await Bun.file(join(output, "table/table_use_schema.go")).exists()).toBe(false);
});

test("rejects a normalized model filename in raw output before changing files", async () => {
  const root = await directory();
  const output = join(root, "database", schema);
  await Bun.write(join(output, "model/documents.model.go"), model);
  await Bun.write(join(output, "table/documents.go"), table);
  await Bun.write(join(output, "table/table_use_schema.go"), helper);
  const before = await databaseSnapshot(root);
  await expect(normalizeDatabaseOutput(root, schema)).rejects.toThrow("output files");
  expect(await databaseSnapshot(root)).toEqual(before);
});

test("database drift includes changed, removed and added files without changing originals", async () => {
  const before = await directory(), after = await directory();
  await Bun.write(join(before, "model/documents.go"), model);
  await Bun.write(join(before, "table/documents.go"), "old");
  await Bun.write(join(after, "table/documents.go"), "new");
  await Bun.write(join(after, "model/documents.model.go"), model);
  expect(changedFiles(await databaseSnapshot(before), await databaseSnapshot(after))).toEqual(["model/documents.go", "model/documents.model.go", "table/documents.go"]);
  expect(await Bun.file(join(before, "model/documents.go")).text()).toBe(model);
  expect(await Bun.file(join(before, "table/documents.go")).text()).toBe("old");
});

test("generation drops only a schema it successfully created", async () => {
  const calls: string[] = [];
  await expect(withOwnedGenerationSchema(async () => { throw new Error("create failed"); }, async () => { calls.push("work"); }, async () => { calls.push("drop"); })).rejects.toThrow("create failed");
  expect(calls).toEqual([]);
  const failure = new Error("generation failed"), reported: unknown[] = [];
  await expect(withOwnedGenerationSchema(async () => { calls.push("create"); }, async () => { calls.push("work"); throw failure; }, async () => { calls.push("drop"); throw new Error("cleanup failed"); }, error => reported.push(error))).rejects.toBe(failure);
  expect(calls).toEqual(["create", "work", "drop"]);
  expect(reported).toHaveLength(1);
});

test("cancellation after creation still runs independent cleanup", async () => {
  const controller = new AbortController();
  let dropped = false;
  await expect(withOwnedGenerationSchema(async () => { controller.abort(new Error("interrupted")); }, async () => controller.signal.throwIfAborted(), async () => { dropped = true; })).rejects.toThrow("interrupted");
  expect(dropped).toBe(true);
});

test("normalizes every explicit identity table constructor", () => {
 for (const name of databaseTables) {
  const type = tableType(name);
  const output = normalizeDatabaseFile(fixture(name, "table"), `table/${name}.go`, schema);
  expect(output).toContain(`new${type}Table("", "${name}", "")`);
  expect(output).not.toContain(schema);
  expect(() => normalizeDatabaseFile(fixture(name, "table").replace(`new${type}Table`, "changed"), `table/${name}.go`, schema)).toThrow("constructor");
 }
});
