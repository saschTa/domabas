export async function databaseSnapshot(directory: string): Promise<Map<string, string>> {
  const result = new Map<string, string>();
  async function walk(path: string): Promise<void> {
    if (!existsSync(path)) return;
    for (const entry of await readdir(path, { withFileTypes: true })) {
      const file = join(path, entry.name);
      if (entry.isDirectory()) await walk(file);
      else if (entry.isFile()) result.set(relative(directory, file).split(sep).join("/"), await sha256(file));
      else throw new Error("Unexpected non-file database generator output.");
    }
  }
  await walk(directory);
  return result;
}

export function normalizeDatabaseFile(source: string, file: string, schema: string): string {
  if (!rawDatabaseFiles.includes(file) || !/^domabas_generate_[a-f0-9]{32}$/.test(schema)) throw new Error("Unexpected database generator output shape.");
  if (!source.includes("Code generated by go-jet DO NOT EDIT.")) throw new Error("Missing Jet generated marker.");
  if (file.startsWith("table/")) {
    const table = databaseTables.find(name => file === `table/${name}.go`)!;
    const type = tableTypes[table];
    const constructor = `var ${type} = new${type}Table("${schema}", "${table}", "")`;
    if (source.split(constructor).length !== 2) throw new Error("Expected exactly one Jet schema constructor.");
    source = source.replace(constructor, `var ${type} = new${type}Table("", "${table}", "")`);
  }
  if (source.includes(schema) || /domabas_generate_[a-f0-9]+/.test(source)) throw new Error("Unexpected generated schema reference.");
  return normalizeGeneratedComments(source, "go");
}

export function validateSchemaHelper(source: string): void {
  const helper = normalizeGeneratedComments(source, "go");
  const expected = '// Code generated by go-jet DO NOT EDIT.\n\npackage table\n\nfunc UseSchema(schema string) {\n' + databaseTables.map(table => `\t${tableTypes[table]} = ${tableTypes[table]}.FromSchema(schema)\n`).join("") + '}\n';
  if (helper !== expected) throw new Error("Unexpected Jet global schema helper.");
}

export async function databaseOutput(directory: string, schema: string): Promise<string> {
  const databases = await readdir(directory, { withFileTypes: true });
  if (databases.length !== 1 || !databases[0]!.isDirectory()) throw new Error("Unexpected Jet database output directory.");
  const prefix = `${databases[0]!.name}/${schema}/`;
  const paths = [...(await databaseSnapshot(directory)).keys()].sort();
  if (JSON.stringify(paths) !== JSON.stringify([...rawDatabaseFiles, schemaHelperFile].map(file => prefix + file).sort())) throw new Error("Unexpected Jet output files.");
  return join(directory, databases[0]!.name, schema);
}

export async function normalizeDatabaseOutput(directory: string, schema: string): Promise<string> {
  const output = await databaseOutput(directory, schema);
  const schemaHelper = join(output, schemaHelperFile);
  validateSchemaHelper(await Bun.file(schemaHelper).text());
  const normalized = [];
  for (const [raw, file] of Object.entries(databaseFileNames)) {
    const path = join(output, raw);
    normalized.push({ path, target: join(output, file), source: normalizeDatabaseFile(await Bun.file(path).text(), raw, schema) });
  }
  for (const { path, target, source } of normalized) {
    await Bun.write(path, source);
    if (path !== target) await rename(path, target);
  }
  await rm(schemaHelper);
  return output;
}

export async function withOwnedGenerationSchema(
  create: () => Promise<void>, work: () => Promise<void>, drop: () => Promise<void>,
  reportCleanup?: (error: unknown) => void,
): Promise<void> {
  let owned = false;
  await withCleanup(async () => { await create(); owned = true; await work(); }, async () => { if (owned) await drop(); }, reportCleanup);
}

async function schemaStatement(databaseURL: string, statement: string): Promise<void> {
  let sql: SQL | undefined;
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    sql = new SQL(databaseURL, { max: 1, connectionTimeout: 5, connection: { statement_timeout: 10000, lock_timeout: 5000 } });
    await Promise.race([
      sql.unsafe(statement),
      new Promise<never>((_, reject) => { timer = setTimeout(() => reject(new Error("Schema operation timed out.")), 15000); }),
    ]);
  } catch {
    throw new Error("Database generation schema operation failed; check database connectivity and schema permissions.");
  } finally {
    clearTimeout(timer);
    await sql?.close({ timeout: 1 });
  }
}

export async function generateDatabase(scope: ProcessScope, check = false, env: Environment = environment()): Promise<void> {
  const databaseURL = env.TEST_DATABASE_URL || required(env, "DATABASE_URL");
  let isolated: URL;
  try { isolated = new URL(databaseURL); }
  catch { throw new Error("Database generation requires a PostgreSQL connection URL."); }
  if (!["postgres:", "postgresql:"].includes(isolated.protocol)) throw new Error("Database generation requires a PostgreSQL connection URL.");
  const schema = `domabas_generate_${crypto.randomUUID().replaceAll("-", "")}`;
  isolated.searchParams.set("search_path", schema);
  const temporary = await mkdtemp(join(tmpdir(), "domabas-generate-db-"));
  await withCleanup(async () => {
    scope.signal.throwIfAborted();
    await withOwnedGenerationSchema(
      () => schemaStatement(databaseURL, `CREATE SCHEMA "${schema}"`),
      async () => {
        const go = command("go"), backend = join(ROOT, "backend");
        const migration = await scope.capture([go, "run", "./cmd/migrate"], { cwd: backend, env: { ...env, DATABASE_URL: isolated.toString(), DOMABAS_ENV_FILE: "" } }, 120000);
        if (migration.code) throw new Error("Database generation migration failed; run the migration tests for details.");
        const generated = await scope.capture([go, "tool", "jet", "-source=postgres", `-dsn=${isolated}`, `-schema=${schema}`, `-tables=${databaseTables.join(",")}`, "-ignore-views=*", "-ignore-enums=*", `-path=${temporary}`], { cwd: backend, env }, 120000);
        if (generated.code) throw new Error("Jet database generation failed; check the pinned tool and database connection.");
        const output = await normalizeDatabaseOutput(temporary, schema);
        await scope.run([command("gofmt"), "-w", ...databaseFiles.map(file => join(output, file))]);
        const target = join(backend, "internal/data/postgres/generated");
        if (check) {
          const changed = changedFiles(await databaseSnapshot(target), await databaseSnapshot(output));
          if (changed.length) throw new Error(`Generated database files differ; run task generate:db and commit the output:\n${changed.join("\n")}`);
        } else {
          await mkdir(join(backend, "internal/data/postgres"), { recursive: true });
          await replaceDirectory(output, target);
        }
        console.log(check ? "Generated database code matches canonical migrations." : "Generated Jet database models and tables.");
      },
      async () => {
        try { await scope.close(); }
        finally { await schemaStatement(databaseURL, `DROP SCHEMA "${schema}" CASCADE`); }
      },
    );
  }, () => rm(temporary, { recursive: true, force: true }));
}

if (import.meta.main) await runCLI(async scope => {
  const { values } = parseArgs({ args: Bun.argv.slice(2), options: { check: { type: "boolean", default: false }, help: { type: "boolean", short: "h" } } });
  if (values.help) { console.log("Usage: bun --no-env-file scripts/generation/generate-database.ts [--check]"); return; }
  await generateDatabase(scope, values.check);
});
