import { expect, test } from "bun:test";
import { normalizeGeneratedComments } from "./generated-comments.ts";

test("generated cleanup preserves Go build constraints, provenance, tags and literal URLs", () => {
  const source = '//go:build go1.22\n\n// Package docs.\n// Code generated by the generator. DO NOT EDIT.\npackage api\n\n// Response model.\ntype Response struct { URL string `json:"url"` }\nconst endpoint = "https://example.test//api"\n';
  const output = normalizeGeneratedComments(source, "go");
  expect(output).toContain("//go:build go1.22\n\n");
  expect(output).toContain("// Code generated by the generator. DO NOT EDIT.");
  expect(output).toContain('`json:"url"`');
  expect(output).toContain('"https://example.test//api"');
  expect(output).not.toContain("Package docs");
  expect(output).not.toContain("Response model");
  expect(normalizeGeneratedComments(output, "go")).toBe(output);
});

test("generated cleanup preserves Dart language and analyzer instructions", () => {
  const source = '// AUTO-GENERATED FILE, DO NOT MODIFY!\n// @dart=2.18\n// ignore_for_file: unused_import\n/// Model docs.\nclass Model {\n  // ignore: unnecessary_parenthesis\n  String value = r"//literal"; // ignore: unused_field\n}\n';
  const output = normalizeGeneratedComments(source, "dart");
  expect(output).toContain("// @dart=2.18");
  expect(output).toContain("// ignore_for_file: unused_import");
  expect(output).toContain("// ignore: unnecessary_parenthesis");
  expect(output).toContain('r"//literal"; // ignore: unused_field');
  expect(output).not.toContain("Model docs");
  expect(normalizeGeneratedComments(source + "\n  \n", "dart")).toBe(output);
});

test("new multiline literal layouts fail without publishing altered code", () => {
  expect(() => normalizeGeneratedComments('package api\nconst text = `line\n//literal\n`\n', "go")).toThrow("unsupported multiline");
  expect(() => normalizeGeneratedComments("const text = r'''line\n//literal\n''';\n", "dart")).toThrow("unsupported multiline");
});
